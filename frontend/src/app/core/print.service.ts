import { Injectable } from "@angular/core";

@Injectable({
  providedIn: "root",
})
export class PrintService {
  print(title: string, subtitle: string, body: string): void {
    const win = window.open("", "_blank", "width=1000,height=800");

    if (!win) {
      return;
    }

    win.document.write(`
      <!doctype html>
      <html>
      <head>
        <meta charset="utf-8">
        <title>${this.escape(title)}</title>

        <style>
          @page {
            size: A4;
            margin: 16mm 14mm 18mm;
          }

          * {
            box-sizing: border-box;
          }

          html, body {
            margin: 0;
            padding: 0;
            background: white;
            color: #292524;
            font-family:
              Inter,
              ui-sans-serif,
              system-ui,
              -apple-system,
              BlinkMacSystemFont,
              "Segoe UI",
              sans-serif;
            font-size: 10.5pt;
            line-height: 1.5;
          }

          body {
            padding: 0;
          }

          .report {
            max-width: 180mm;
            margin: 0 auto;
          }

          .header {
            border-bottom: 2px solid #d97706;
            padding-bottom: 12px;
            margin-bottom: 18px;
          }

          .brand {
            font-size: 10pt;
            font-weight: 700;
            letter-spacing: .12em;
            text-transform: uppercase;
            color: #b45309;
          }

          h1 {
            margin: 4px 0 2px;
            font-size: 25pt;
            line-height: 1.15;
            color: #1c1917;
          }

          .subtitle {
            color: #78716c;
            font-size: 10pt;
          }

          h2 {
            margin: 22px 0 8px;
            padding-bottom: 5px;
            border-bottom: 1px solid #e7e5e4;
            font-size: 14pt;
            color: #292524;
          }

          h3 {
            margin: 12px 0 5px;
            font-size: 11pt;
            color: #44403c;
          }

          .facts {
            display: grid;
            grid-template-columns: repeat(4, 1fr);
            gap: 8px;
            margin: 14px 0 18px;
          }

          .fact {
            border: 1px solid #e7e5e4;
            border-radius: 7px;
            padding: 9px;
            background: #fafaf9;
          }

          .fact-label {
            font-size: 7.5pt;
            text-transform: uppercase;
            letter-spacing: .06em;
            color: #78716c;
          }

          .fact-value {
            margin-top: 2px;
            font-weight: 650;
            color: #292524;
          }

          table {
            width: 100%;
            border-collapse: collapse;
            margin: 8px 0 16px;
          }

          th {
            text-align: left;
            font-size: 8pt;
            text-transform: uppercase;
            letter-spacing: .04em;
            color: #78716c;
            background: #f5f5f4;
          }

          th, td {
            border-bottom: 1px solid #e7e5e4;
            padding: 6px 7px;
            vertical-align: top;
          }

          .card {
            border: 1px solid #e7e5e4;
            border-radius: 7px;
            padding: 10px 12px;
            margin: 8px 0;
            break-inside: avoid;
          }

          .muted {
            color: #78716c;
          }

          .accent {
            color: #b45309;
            font-weight: 650;
          }

          .pill {
            display: inline-block;
            border-radius: 999px;
            padding: 2px 7px;
            background: #f5f5f4;
            color: #57534e;
            font-size: 8pt;
          }

          .note {
            white-space: pre-wrap;
          }

          .page-break {
            break-before: page;
          }

          .footer {
            margin-top: 25px;
            padding-top: 8px;
            border-top: 1px solid #e7e5e4;
            color: #a8a29e;
            font-size: 7.5pt;
          }

          ul, ol {
            padding-left: 20px;
          }

          li {
            margin-bottom: 5px;
          }

          @media print {
            .no-print {
              display: none !important;
            }
          }
        </style>
      </head>

      <body>
        <main class="report">
          <header class="header">
            <div class="brand">FermentLab</div>
            <h1>${this.escape(title)}</h1>
            <div class="subtitle">${this.escape(subtitle)}</div>
          </header>

          ${body}

          <footer class="footer">
            Generated by FermentLab · ${new Date().toLocaleString()}
          </footer>
        </main>
      </body>
      </html>
    `);

    win.document.close();

    win.onload = () => {
      setTimeout(() => {
        win.focus();
      }, 250);
    };
  }

  private escape(value: unknown): string {
    return String(value ?? "")
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;")
      .replace(/'/g, "&#039;");
  }
}
